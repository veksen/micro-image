/**
 * The browser benchmark's model: what each page contains, and how a fetch is
 * read back out of a URL. Pure, so the runner and the page agree on it and the
 * suite can pin it without a browser.
 */

/**
 * Every markup row shares one ladder, so a difference between rows is the
 * `sizes` they emit and nothing else. This is Next.js 16's default
 * `imageSizes` + `deviceSizes` (`next/dist/shared/lib/image-config.js`), which
 * makes the `next/image` row's candidates identical too. Which ladder is right
 * is ADR 0003's question, not this benchmark's.
 */
export const ladder = [
  32, 48, 64, 96, 128, 256, 384, 640, 750, 828, 1080, 1200, 1920, 2048, 3840,
] as const;

/** Every candidate below the intrinsic width, then the intrinsic width itself. */
export function capLadder(intrinsicWidth: number): number[] {
  return [...ladder.filter((width) => width < intrinsicWidth), intrinsicWidth];
}

export interface Fixture {
  name: "large" | "small";
  width: number;
  height: number;
}

/**
 * `large` is the Unsplash photo already in `apps/docs/public`. `small` is the
 * same photo at 800px, generated by the proxy before a run, so the intrinsic
 * cap actually cuts the ladder.
 */
export const fixtures: Record<Fixture["name"], Fixture> = {
  large: { name: "large", width: 5272, height: 3948 },
  small: { name: "small", width: 800, height: 599 },
};

/** Images per page: one eager image in the layout, then a lazy grid below the fold. */
export const lazyCount = 6;
export const imageCount = 1 + lazyCount;

/** One copy per image, so every fetch can be attributed to the image that made it. */
export function fixturePath(fixture: Fixture, index: number): string {
  return `/bench/${fixture.name}-${index}.jpg`;
}

export const layoutNames = ["full", "column", "grid", "thumb", "full-small"] as const;
export type LayoutName = (typeof layoutNames)[number];

export interface Layout {
  fixture: Fixture;
  /** Inline style of the box the eager image fills. */
  eagerBox: Record<string, string>;
  /**
   * The eager box's width as a `sizes` value: what a perfect build would bake.
   * Media queries rather than `min()`, which `sizes` is not guaranteed to parse.
   */
  exactSizes: string;
}

