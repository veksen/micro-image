export const strategyNames = [
  "shipped",
  "pr71",
  "pr71+sizes",
  "bake-100vw",
  "bake-100vw+obs",
  "exact",
  "plain-srcset",
  "next-image",
] as const;
export type StrategyName = (typeof strategyNames)[number];

export function isLayoutName(value: unknown): value is LayoutName {
  return layoutNames.includes(value as LayoutName);
}

export function isStrategyName(value: unknown): value is StrategyName {
  return strategyNames.includes(value as StrategyName);
}

/** The micro-image provider's URL grammar, WebP so its bytes compare with `next/image`'s. */
export function proxyUrl(proxy: string, src: string, width: number): string {
  return `${proxy}?image=${encodeURIComponent(src)}&width=${width}&format=webp&quality=75`;
}

export function srcSet(proxy: string, src: string, fixture: Fixture): string {
  return capLadder(fixture.width)
    .map((width) => `${proxyUrl(proxy, src, width)} ${width}w`)
    .join(", ");
}

export interface ImageFetch {
  /** Which image on the page made it, from the fixture copy in the URL. */
  index: number;
  /** The width the URL asked for, or undefined when it names none. */
  width: number | undefined;
  /** The shipped component's blurred 500px stand-in, not a real candidate. */
  placeholder: boolean;
}

const fixtureInUrl = /\/bench\/(?:large|small)-(\d+)\.jpg/;

/**
 * Reads a proxy URL (`?image=…&width=`) or a `next/image` URL (`?url=…&w=`)
 * back into the image and width it fetched. Anything else is not an image
 * fetch and returns undefined.
 */
export function parseImageFetch(url: string): ImageFetch | undefined {
  const parsed = new URL(url);
  const source = parsed.searchParams.get("image") ?? parsed.searchParams.get("url");
  const match = source === null ? null : fixtureInUrl.exec(source);
  if (match === null) {
    return undefined;
  }

  const width = parsed.searchParams.get("width") ?? parsed.searchParams.get("w");

  return {
    index: Number(match[1]),
    width: width === null ? undefined : Number(width),
    placeholder: parsed.searchParams.has("blur"),
  };
}

/**
 * The width the browser actually delivered over the width the box needed.
 * 1 is exact, above 1 is wasted bytes, below 1 is a blurry image. A fetch
 * wider than the source is served at intrinsic width, so it counts as that.
 */
export function fitRatio(
  fetchedWidth: number,
  intrinsicWidth: number,
  neededWidth: number
): number {
  return Math.min(fetchedWidth, intrinsicWidth) / neededWidth;
}

export function median(values: number[]): number {
  const sorted = [...values].sort((a, b) => a - b);
  const middle = Math.floor(sorted.length / 2);

  return sorted.length % 2 === 1 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2;
}
